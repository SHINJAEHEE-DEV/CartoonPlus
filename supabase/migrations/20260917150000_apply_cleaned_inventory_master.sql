-- 4. Upsert into book_inventories for snu store
insert into public.book_inventories (
  store_id, book_id, volume_range, last_volume, shelf_location, updated_at
)
select
  s.id as store_id,
  b.id as book_id,
  t.volume_range,
  t.last_volume,
  t.shelf_location,
  now()
from temp_cleaned_master t
cross join (select id from public.stores where slug = 'snu') s
join public.books b on b.title = t.title and b.author = t.author
on conflict (store_id, book_id) do update set
  volume_range = excluded.volume_range,
  last_volume = excluded.last_volume,
  shelf_location = excluded.shelf_location,
  updated_at = now();

