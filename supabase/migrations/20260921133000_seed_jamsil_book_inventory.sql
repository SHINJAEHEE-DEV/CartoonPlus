-- 1. Insert newly discovered books into public.books table
insert into public.books (
  title,
  author,
  category,
  normalized_title,
  normalized_author,
  initial_consonants
)
select
  t.title,
  '',
  '',
  lower(regexp_replace(t.title, '[[:space:][:punct:]]', '', 'g')),
  '',
  ''
from temp_jamsil_inventory t
where not exists (
  select 1 from public.books b where b.title = t.title
)
on conflict (title, author) do nothing;

-- 2. Upsert into public.book_inventories for jamsil store
insert into public.book_inventories (
  store_id,
  book_id,
  volume_range,
  last_volume,
  shelf_location,
  updated_at
)
select
  s.id as store_id,
  b.id as book_id,
  t.volume_range,
  t.last_volume,
  t.shelf_location,
  now()
from temp_jamsil_inventory t
cross join (select id from public.stores where slug = 'jamsil') s
join lateral (
  select id from public.books b
  where b.title = t.title
  order by case when b.author <> '' then 0 else 1 end, b.created_at asc
  limit 1
) b on true
on conflict (store_id, book_id) do update set
  volume_range = excluded.volume_range,
  last_volume = excluded.last_volume,
  shelf_location = excluded.shelf_location,
  updated_at = now();
